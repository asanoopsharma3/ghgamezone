/**
 * Find a game by its title, slug, or partial match.
 * Falls back to first game if no match found.
 */
export const getGameByTitleOrSlug = (query) => {
  if (!query) return GAMES_CATALOG[0];
  const q = String(query).toLowerCase().trim();
  const match = GAMES_CATALOG.find(
    (g) =>
      g.title.toLowerCase().includes(q) ||
      g.slug.toLowerCase().includes(q) ||
      q.includes(g.slug.toLowerCase()) ||
      q.includes(g.title.toLowerCase()) ||
      q.includes(g.category.toLowerCase())
  );
  return match || GAMES_CATALOG[0];
};

/**
 * Get games filtered by category (case-insensitive).
 */
export const getGamesByCategory = (category) => {
  if (!category || category.toUpperCase() === "ALL") return GAMES_CATALOG;
  return GAMES_CATALOG.filter(
    (g) => g.category.toLowerCase() === category.toLowerCase()
  );
};

/**
 * Get trending games.
 */
export const getTrendingGames = () => GAMES_CATALOG.filter((g) => g.isTrending);

/**
 * Get new releases.
 */
export const getNewReleases = () => GAMES_CATALOG.filter((g) => g.isNew);
